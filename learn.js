// What is react native ?
// React Native is a framework for building native mobile applications using JavaScript and React. It allows developers to create mobile apps for both iOS and Android platforms using a single codebase, which can save time and resources compared to developing separate apps for each platform. React Native uses native components, which means that the user interface of the app will look and feel like a native app, rather than a web app. This makes it a popular choice for developers who want to create high-quality mobile apps with a great user experience.

// Why use react native ?
// There are several reasons why developers choose to use React Native for mobile app development:
// 1. Cross-platform development: React Native allows developers to write code once and deploy it on both iOS and Android platforms, which can save time and resources compared to developing separate apps for each platform.

// 2. Native performance: React Native uses native components, which means that the user interface of the app will look and feel like a native app, rather than a web app. This can lead to better performance and a better user experience.

// 3. Large community: React Native has a large and active community of developers, which means that there are many resources available for learning and troubleshooting.

// 4. Hot Reloading: React Native allows developers to see the changes they make in real-time without having to rebuild the entire app, which can speed up the development process.

// 5. Cost-effective: React Native can be more cost-effective than developing separate apps for each platform, as it allows developers to reuse code across platforms and reduces the need for specialized skills in each platform's native development environment.


// Expo vs React Native CLI ?
// Expo and React Native CLI are two different tools for building React Native applications.

// Expo is a set of tools and services built around React Native that makes it easier to develop, build, and deploy React Native apps. It provides a development environment with features like hot reloading, a built-in app store for testing, and a set of pre-built components and APIs. Expo also allows developers to build and deploy their apps without needing to set up native development environments for iOS and Android.

// React Native CLI, on the other hand, is a command-line interface for building React Native applications. It provides more flexibility and control over the development process, allowing developers to customize their app's configuration and use native modules. However, it requires developers to set up native development environments for both iOS and Android, which can be more complex and time-consuming than using Expo.

// In summary, Expo is a great choice for developers who want a simpler and faster development experience, while React Native CLI is better suited for developers who need more control and customization over their app's configuration and native modules.




